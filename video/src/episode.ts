import preview from "../../episodes/ep08-full-reference/runtime.preview.json";
import type { ReferenceMascotPose } from "./components/ReferenceMascot";

export type SceneKind = "statement" | "evidence" | "comparison" | "receipt" | "projects";
export type VisualData = {
  headline?: string;
  subline?: string;
  items?: Array<{ label: string; value?: string | number }>;
  /** Local public-relative asset, e.g. evidence/report.png. */
  image?: string;
  pose?: ReferenceMascotPose;
};
export type EpisodeScene = {
  id: string;
  duration_seconds: number;
  title: string;
  narration: string;
  caption_lines?: string[];
  visual?: string;
  note?: string;
  kind?: SceneKind;
  visual_data?: VisualData;
};
export type Episode = {
  title: string;
  fps: number;
  width: number;
  height: number;
  version?: string;
  character_variant?: "reference" | "classic";
  status?: string;
  silent_outro?: { duration_seconds: number; amount_krw: number; basis: string };
  facts?: Record<string, unknown>;
  scenes: EpisodeScene[];
};
export const defaultEpisode = preview.episode as Episode;
export type CaptionCue = { start: number; end: number; text: string };
export type SceneRuntime = {
  id: string;
  duration_seconds: number;
  /** Relative to video/public, e.g. audio/ep08-full-reference/scene.wav. */
  audioSrc: string;
  /** Scene-local seconds, generated by the external TTS pipeline. */
  captions: CaptionCue[];
};
export type EpisodeProps = {
  episode?: Episode;
  sceneRuntime?: SceneRuntime[];
};

export function timelineFor(props: EpisodeProps) {
  const episode = props.episode ?? defaultEpisode;
  if (!(episode.fps > 0 && episode.width > 0 && episode.height > 0) || !episode.scenes.length) {
    throw new Error("Episode needs positive fps/dimensions and at least one scene.");
  }
  const ids = new Set(episode.scenes.map((scene) => scene.id));
  if (ids.size !== episode.scenes.length) throw new Error("Episode scene IDs must be unique.");
  for (const scene of episode.scenes) {
    const image = scene.visual_data?.image;
    if (image && (image.includes(":") || image.startsWith("/") || image.includes("\\") || image.split("/").includes(".."))) {
      throw new Error(`visual_data.image must be public-relative: ${scene.id}`);
    }
  }
  const runtimes = new Map<string, SceneRuntime>();
  for (const runtime of props.sceneRuntime ?? []) {
    if (!ids.has(runtime.id) || runtimes.has(runtime.id)) {
      throw new Error(`Unknown or duplicate runtime scene: ${runtime.id}`);
    }
    if (!Number.isFinite(runtime.duration_seconds) || runtime.duration_seconds <= 0) {
      throw new Error(`Invalid duration for ${runtime.id}`);
    }
    const src = runtime.audioSrc;
    if (src.includes(":") || src.startsWith("/") || src.includes("\\") || src.split("/").includes("..")) {
      throw new Error(`audioSrc must be a local public-relative asset: ${runtime.id}`);
    }
    for (const cue of runtime.captions) {
      if (!Number.isFinite(cue.start) || !Number.isFinite(cue.end) || cue.start < 0 || cue.end <= cue.start || cue.end > runtime.duration_seconds + 0.1) {
        throw new Error(`Invalid scene-local caption interval: ${runtime.id}`);
      }
    }
    runtimes.set(runtime.id, runtime);
  }
  let cursor = 0;
  const scenes = episode.scenes.map((scene) => {
    const runtime = runtimes.get(scene.id);
    const seconds = runtime?.duration_seconds ?? scene.duration_seconds;
    if (!Number.isFinite(seconds) || seconds <= 0) throw new Error(`Invalid duration: ${scene.id}`);
    const frames = Math.max(1, Math.round(seconds * episode.fps));
    const item = { scene, runtime, from: cursor, frames };
    cursor += frames;
    return item;
  });
  const outroFrames = episode.silent_outro ? Math.max(0, Math.round(episode.silent_outro.duration_seconds * episode.fps)) : 0;
  return { episode, scenes, outroFrom: cursor, outroFrames, totalFrames: cursor + outroFrames };
}
